function compareObjects(received: any, expected: any, path: string): boolean {
  if (typeof received !== 'object' || typeof expected !== 'object') {
    if (received === expected) {
      return true;
    }
    console.log(`Difference at ${path}: expected ${expected}, but received ${received}`);
    return false;
  }

  for (const key in expected) {
    if (!(key in received)) {
      continue; // Skip keys that are not in received
    }
    if (!compareObjects(received[key], expected[key], path ? path + '.' + key : key)) {
      return false;
    }
  }

  return true;
}

